#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
build-agents-page — docs/agents.html, the full "Show all" roster.

Run from the repo root after editing tools/agents.json:

    python3 tools/build-agents-page.py
    python3 tools/review-manifest.py

The roster is the production list
(thegrouprealestatess.com/agents/?role=agent&office_id=32810), photos saved
to docs/assets/agents/<slug>.jpg. An agent with a mockup profile page
(docs/agent-<slug>.html) links to it; everyone else links out to production.
"""
import os, json, html

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(ROOT, "docs")
DATA = json.load(open(os.path.join(ROOT, "tools", "agents.json"), encoding="utf-8"))
AGENTS = DATA["agents"]

def e(s):
    return html.escape(str(s), quote=True)

def phone(p):
    return "%s.%s.%s" % (p[:3], p[3:6], p[6:]) if p and len(p) == 10 else ""

def tile(a, n):
    local = "agent-%s.html" % a["slug"]
    if os.path.exists(os.path.join(DOCS, local)):
        href, ext, go = local, "", 'View profile <span aria-hidden="true">&rarr;</span>'
    else:
        href, ext, go = a["production"], ' target="_blank" rel="noopener"', 'Profile at The Group <span aria-hidden="true">&#8599;</span>'
    role = "Team" if a["kind"] == "team" else "Broker"
    tel = phone(a["phone"])
    tel_html = '<span class="agent__tel">%s</span>' % tel if tel else ""
    return """        <a class="agent agent--roster" href="{href}"{ext} data-name="{name}" data-kind="{kind}" data-initial="{initial}" data-langs="{langs}"{hidden}>
          <div class="agent__photo">
            <img src="{photo}" alt="{name}" loading="lazy" onerror="this.remove()" />
            <span class="agent__veil" aria-hidden="true"></span>
          </div>
          <div class="agent__meta">
            <span class="agent__id"><span class="agent__name">{name}</span><span class="agent__role">{role}</span></span>
            <span class="agent__num">{n:02d}</span>
          </div>
          <div class="agent__foot">{tel}<span class="agent__go">{go}</span></div>
        </a>""".format(href=e(href), ext=ext, name=e(a["name"]), kind=a["kind"], photo=e(a["photo"]),
                      role=role, n=n, tel=tel_html, go=go, initial=a["lastInitial"],
                      langs=e(" ".join(a["languages"])), hidden="")

def select(id_, label, options):
    opts = "\n".join('              <option value="%s">%s</option>' % (e(v), e(t)) for v, t in options)
    return """        <label class="pbar__seg">
          <span class="mini-label">%s</span>
          <span class="pbar__select">
            <select id="%s">
%s
            </select>
            <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" aria-hidden="true"><path d="M6 9l6 6 6-6"/></svg>
          </span>
        </label>""" % (label, id_, opts)

LANGS = ["English", "Spanish", "French", "Japanese"]
selects = "\n".join([
    select("roster-kind", "Show", [("all", "All Brokers"), ("team", "Teams")]),
    select("roster-initial", "Last name initial", [("", "Any")] + [(c, c) for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ"]),
    select("roster-lang", "Language", [("", "Any language")] + [(l, l) for l in LANGS]),
])

n_team = sum(a["kind"] == "team" for a in AGENTS)
n_broker = len(AGENTS) - n_team
tiles = "\n".join(tile(a, i + 1) for i, a in enumerate(AGENTS))

page = """<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <meta name="robots" content="noindex, nofollow, noarchive, noimageindex" />
  <title>All Agents — The Group, Steamboat Springs</title>
  <meta name="description" content="Every broker and team at The Group, Steamboat Springs." />
  <link rel="preconnect" href="https://fonts.googleapis.com" />
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
  <link href="https://fonts.googleapis.com/css2?family=Marcellus&family=Inter:wght@300;400;500&display=swap" rel="stylesheet" />
  <link rel="stylesheet" href="css/styles.css" />
  <link rel="stylesheet" href="css/guide-page.css" />
  <link rel="stylesheet" href="css/review.css" />
</head>
<body>
  <!-- Generated by tools/build-agents-page.py from tools/agents.json. Edit those, not this. -->

  <!-- ============================ PAGE HEAD ============================ -->
  <div class="pagehead" id="s-page-header" data-review="Page header">
    <nav class="nav">
      <div class="nav__brand">
        <a href="index.html"><img class="nav__logo" src="assets/svg/logo.svg" alt="The Group" /></a>
        <span class="nav__loc">Steamboat Springs, CO</span>
      </div>
      <div class="nav__links">
        <a href="index.html#agents">The People</a>
        <a href="index.html#buyers">Buyers Now</a>
        <a href="index.html#life">Lifestyle</a>
        <a href="index.html#guides">How We Work</a>
        <a href="index.html#ready">Search</a>
      </div>
    </nav>
    <div class="pagehead__inner">
      <a class="crumb" href="index.html#agents"><span>←</span> The People</a>
      <p class="eyebrow eyebrow--bright">All Agents</p>
      <h2 class="h2">Everyone at The Group, Steamboat.</h2>
      <p class="lede">{total} brokers and teams, every one of them local. Find the person you'd want on your side of the table.</p>
    </div>
  </div>

  <!-- ============================ ROSTER ============================ -->
  <section class="section agents roster" id="s-roster" data-review="Roster">
    <div class="container">
      <div class="pbar pbar--roster">
        <label class="pbar__seg pbar__seg--name">
          <span class="mini-label">Find by name</span>
          <span class="pbar__input">
            <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" aria-hidden="true"><circle cx="11" cy="11" r="7"/><path d="M21 21l-4.3-4.3"/></svg>
            <input type="text" id="roster-search" placeholder="Type a name…" autocomplete="off" />
          </span>
        </label>
{selects}
      </div>
      <div class="pbar__status">
        <p class="pbar__count" id="roster-count" aria-live="polite">Showing {total} brokers</p>
        <button class="pbar__clear" type="button" id="roster-clear" hidden>Clear filters <span aria-hidden="true">&times;</span></button>
      </div>

      <div class="agent-grid agent-grid--roster" id="roster-grid">
{tiles}
      </div>
      <p class="agents__empty" id="roster-empty" hidden>No one matches — try another name, or clear the filters.</p>
      <p class="mls-note roster__note">Roster from the production agents page ({source}), {snap}.</p>
    </div>
  </section>

  <!-- ============================ FOOTER ============================ -->
  <footer class="footer footer--home" id="footer" data-review="Footer">
    <div class="footer__box">
      <hr class="footer__rule" />
      <div class="footer__inner">
      <a href="about-the-group-steamboat.html">About Us</a>
      <a href="privacy-policy.html">Privacy</a>
      <a href="contact.html">Contact</a>
      <a href="readme.html">Readme</a>
      </div>
      <hr class="footer__rule" />
      <div class="footer__fine">
        <p class="footer__copy">© 2026 The Group Real Estate LLC. All rights reserved.</p>
      </div>
    </div>
  </footer>

  <script src="js/roster.js" defer></script>
  <!-- Review overlay: add ?review=1 to any page to switch it on -->
  <script src="js/review-manifest.js" defer></script>
  <script src="js/review.js" defer></script>

</body>
</html>
""".format(total=len(AGENTS), brokers=n_broker, teams=n_team, tiles=tiles, selects=selects,
           source=e(DATA["source"].replace("https://", "")), snap=e(DATA["snapshot"]))

open(os.path.join(DOCS, "agents.html"), "w", encoding="utf-8").write(page)
print("wrote docs/agents.html — %d agents (%d brokers, %d teams)" % (len(AGENTS), n_broker, n_team))
